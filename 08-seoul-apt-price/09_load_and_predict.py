# 서울 아파트 가격 예측 모델 (랜덤포레스트) 불러와서 예측하는 예시
# 필요한 파일: 이 파일(09_load_and_predict.py) + rf_model.joblib (같은 폴더)
#   rf_model.joblib을 열 때 버전 경고가 나오면  python 08_save_model.py  로 모델을 새로 만든다
# 필요한 프로그램: 파이썬 3, scikit-learn, pandas
#   설치: 터미널(명령 프롬프트)에서  pip install scikit-learn pandas
# 실행: 터미널에서  python 09_load_and_predict.py
# ============================================================

# 운영체제 경로를 다루는 도구(os)를 불러온다 — 파일 위치를 자동으로 찾기 위함
import os
# 학습된 모델을 파일로 저장/불러오는 도구(joblib)를 불러온다
import joblib
# 표(데이터프레임)를 다루는 도구(pandas)를 pd라는 별명으로 불러온다
import pandas as pd

# 이 파이썬 파일이 있는 폴더의 전체 경로를 구한다 (어디서 실행해도 파일을 찾도록)
BASE = os.path.dirname(os.path.abspath(__file__))
# 그 폴더 안의 모델 파일 경로를 만든다
MODEL_PATH = os.path.join(BASE, "rf_model.joblib")

# 모델 파일을 열어 번들(꾸러미)에 담는다 — 안에는 모델과 특성 목록 등이 들어있다
bundle = joblib.load(MODEL_PATH)
# 번들에서 학습된 모델(랜덤포레스트)을 꺼낸다
model = bundle["model"]
# 번들에서 특성(열) 목록을 꺼낸다 — 예측할 때 열 순서를 똑같이 맞추기 위해 필요
cols = bundle["feature_columns"]
# 모델 정보(학습일, 버전, 성적)를 화면에 출력한다
print(f"모델 정보: 학습일 {bundle['trained_on']}, sklearn {bundle['sklearn_version']}, "
      f"테스트 R² {bundle['test_r2']:.4f}, MAE {bundle['test_mae']:,.0f}만원")

# 예측하고 싶은 아파트 정보를 표(DataFrame)로 만든다 — 아래 숫자들을 바꿔 보면 결과가 달라진다
new = pd.DataFrame([
    # 첫 번째 아파트: 강남구 대치동 84.9㎡ 10층 2015년 건축
    {"자치구명": "강남구", "법정동명": "대치동", "전용면적": 84.9, "층": 10, "건축년도": 2015,
     "계약일": "20260101", "신고구분": "중개거래"},
    # 두 번째 아파트: 도봉구 창동 59.9㎡ 3층 2000년 건축
    {"자치구명": "도봉구", "법정동명": "창동", "전용면적": 59.9, "층": 3, "건축년도": 2000,
     "계약일": "20260101", "신고구분": "직거래"},
])

# 계약일(YYYYMMDD 글자)을 진짜 날짜 형식으로 바꾼다
new["계약일"] = pd.to_datetime(new["계약일"], format="%Y%m%d")
# 모델이 학습 때 쓴 기준일(2024-11-15)도 날짜 형식으로 만든다
기준일 = pd.to_datetime("20241115", format="%Y%m%d")
# 계약일이 기준일로부터 며칠 뒤인지 계산해 '계약일수' 열을 만든다 (학습 때와 동일한 변환)
new["계약일수"] = (new["계약일"] - 기준일).dt.days

# 모델에 넣을 숫자 열 4개만 골라낸다
X_new = new[["전용면적", "층", "건축년도", "계약일수"]].copy()
# 입력한 법정동이 학습 데이터에 있던 동인지 확인한다 — 없는 동은 위치 정보가 빠진 채 예측되므로 경고
동 = new["자치구명"] + " " + new["법정동명"]
for d in 동[~동.isin(bundle["dong_list"])]:
    print(f"⚠ '{d}'은(는) 학습 데이터에 없는 법정동입니다. 이름을 확인하세요 (예측 정확도가 떨어집니다).")
# 글자 열(자치구명, 신고구분, 법정동)을 원핫 인코딩(0/1 열)으로 바꿔 옆에 붙인다
# 주의: 여기서는 drop_first를 쓰지 않는다. 예측할 몇 줄만으로 첫 칸을 빼면 학습 때와 다른 칸이 빠질 수 있다.
#       (학습 때 빠진 기준 칸은 바로 아래 reindex에서 자동으로 사라진다)
더미 = pd.get_dummies(new[["자치구명", "신고구분"]])
동더미 = pd.get_dummies(동, prefix="동")
X_new = pd.concat([X_new, 더미, 동더미], axis=1)
# 학습 때 있던 열과 똑같은 순서로 맞춘다 — 학습 때 없던 열은 0으로 채운다
X_new = X_new.reindex(columns=cols, fill_value=0)

# 모델로 예측을 실행하고, 결과(만원 단위)를 구한다
new["예측금액_만원"] = model.predict(X_new)
# 예측값을 100만원 단위로 반올림해 보기 좋게 만든다 (금액 단위가 만원이므로)
new["예측금액_만원"] = new["예측금액_만원"].round(-2)
# 아파트 정보와 예측 결과를 화면에 표로 출력한다
print(new[["자치구명", "법정동명", "전용면적", "층", "건축년도", "예측금액_만원"]].to_string(index=False))
